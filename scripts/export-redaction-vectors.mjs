function fail(message) {
  console.error(message);
  process.exitCode = 1;
}

function buildVectors() {
  const seenNames = new Set();
  const seenInputs = new Set();
  return CASES.map((entry) => {
    const mayBeTruncated = entry.may_be_truncated === true;
    if (seenNames.has(entry.name)) throw new Error(`duplicate vector name: ${entry.name}`);
    seenNames.add(entry.name);
    const inputKey = `${mayBeTruncated ? "1" : "0"}:${entry.input}`;
    if (seenInputs.has(inputKey)) throw new Error(`duplicate vector input: ${entry.name}`);
    seenInputs.add(inputKey);
    return {
      name: entry.name,
      input: entry.input,
      may_be_truncated: mayBeTruncated,
      expected: redactSecretsAtBoundary(entry.input, { mayBeTruncated }),
    };
  }).sort((left, right) => (left.name < right.name ? -1 : left.name > right.name ? 1 : 0));
}

function serialize(vectors) {
  return `${JSON.stringify(vectors, null, 2)}\n`;
}

function readExisting() {
  try {
    return readFileSync(outputPath, "utf8");
  } catch {
    return undefined;
  }
}

function summarizeDiff(vectors, existingText) {
  let existing;
  try {
    existing = JSON.parse(existingText);
  } catch {
    return ["vectors file is not valid JSON"];
  }
  if (!Array.isArray(existing)) return ["vectors file is not a JSON array"];

  const generatedByName = new Map(vectors.map((vector) => [vector.name, vector]));
  const existingByName = new Map(
    existing.filter((vector) => vector !== null && typeof vector === "object" && typeof vector.name === "string")
      .map((vector) => [vector.name, vector]),
  );
  const added = [...generatedByName.keys()].filter((name) => !existingByName.has(name)).sort();
  const removed = [...existingByName.keys()].filter((name) => !generatedByName.has(name)).sort();
  const changed = [...generatedByName.keys()]
    .filter((name) => existingByName.has(name)
      && JSON.stringify(existingByName.get(name)) !== JSON.stringify(generatedByName.get(name)))
    .sort();

  const lines = [
    `vectors file is out of date: ${added.length} added, ${removed.length} removed, ${changed.length} changed`,
  ];
  for (const [label, names] of [["added", added], ["removed", removed], ["changed", changed]]) {
    if (names.length > 0) lines.push(`  ${label}: ${names.join(", ")}`);
  }
  if (added.length === 0 && removed.length === 0 && changed.length === 0) {
    lines.push("  content matches; formatting or key order differs");
  }
  return lines;
}

const vectors = buildVectors();
const serialized = serialize(vectors);
const existingText = readExisting();
// Compare line endings loosely: a checkout with CRLF translation must not
// report a stale file when every vector still matches.
const existingComparable = existingText?.replace(/\r\n/gu, "\n");

if (process.argv.includes("--check")) {
  if (existingText === undefined) {
    fail(`vectors file is missing: ${outputPath}\nrun: node scripts/export-redaction-vectors.mjs`);
  } else if (existingComparable !== serialized) {
    for (const line of summarizeDiff(vectors, existingText)) console.error(line);
    console.error("run: node scripts/export-redaction-vectors.mjs");
    process.exitCode = 1;
  } else {
    console.log(`vectors file is current (${vectors.length} vectors)`);
  }
} else {
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, serialized, "utf8");
  console.log(`wrote ${vectors.length} vectors to ${outputPath}`);
}
